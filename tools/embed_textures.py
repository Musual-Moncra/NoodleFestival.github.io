"""Embed the 3D product textures as data URIs in js/products-textures.js.

Chrome refuses image files as WebGL textures when the page is opened from file://,
so index.html loads this script only in that case. Re-run after prepare_products.py:
    cd tools && npm run textures
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PRODUCTS = json.loads((ROOT / "assets/products/products.json").read_text(encoding="utf-8"))

paths = set()
for prod in PRODUCTS:
    # The 3D models only sample wraps + lids for cups/bowls and the front photo for packs.
    keys = ("front",) if prod["type"] == "pack" else ("wrap", "lid")
    paths.update(prod[k] for k in keys if prod.get(k))

entries = {}
for rel in sorted(paths):
    data = base64.b64encode((ROOT / rel).read_bytes()).decode("ascii")
    entries[rel] = f"data:image/webp;base64,{data}"

out = ROOT / "js/products-textures.js"
out.write_text(
    "// Generated by tools/embed_textures.py — do not edit.\n"
    f"window.MGF_TEXTURES = {json.dumps(entries)};\n",
    encoding="utf-8",
)
print(f"{len(entries)} textures -> {out.relative_to(ROOT)} ({out.stat().st_size / 1e6:.1f} MB)")
